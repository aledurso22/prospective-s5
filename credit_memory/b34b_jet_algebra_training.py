def make_W(seed, r, y_dim=8):
    rng = np.random.RandomState(seed)
    return jnp.array(rng.randn(y_dim, r) * (1.0 / np.sqrt(r)))


def make_sequence(seed, T, r):
    rng = np.random.RandomState(seed)
    h0 = jnp.array(rng.randn(r) * 0.15)
    xs = jnp.array(rng.randn(T, X_DIM) * 0.6)
    return h0, xs


def teacher_targets(h0, theta_star, xs, gen_params, r, W):
    Hs = rollout_h(h0, theta_star, xs, gen_params, r)
    return Hs @ W.T


def loss_mse(theta, h0, xs, targets, gen_params, r, W):
    Hs = rollout_h(h0, theta, xs, gen_params, r)
    Ys = Hs @ W.T
    return jnp.mean(0.5 * jnp.sum((Ys - targets) ** 2, axis=1))


def full_rtrl_grad_mse(theta, h0, xs, targets, gen_params, r, W):
    T = xs.shape[0]
    h = h0
    S = jnp.zeros((r, r), dtype=jnp.float64)
    g_total = jnp.zeros(r, dtype=jnp.float64)
    loss_total = 0.0
    S_traj = []
    for t in range(T):
        x_t = xs[t]
        J_t = jax.jacobian(lambda hh: h_step(hh, theta, x_t, gen_params, r))(h)
        G_t = jax.jacobian(lambda th: h_step(h, th, x_t, gen_params, r))(theta)
        S = J_t @ S + G_t
        S_traj.append(S)
        h_next = h_step(h, theta, x_t, gen_params, r)
        y = W @ h_next
        diff = y - targets[t]
        loss_total = loss_total + 0.5 * jnp.sum(diff ** 2)
        dl_dh = W.T @ diff
        g_total = g_total + dl_dh @ S
        h = h_next
    return g_total / T, loss_total / T, S_traj


def reduced_algebra_grad_mse(theta, h0, xs, targets, gen_params, r, W):
    T = xs.shape[0]
    h = h0
    s = jnp.zeros(r, dtype=jnp.float64)
    g_total = jnp.zeros(r, dtype=jnp.float64)
    loss_total = 0.0
    for t in range(T):
        x_t = xs[t]
        a_t, b_t, kappa_t, c_t = gen_forward(x_t, gen_params, r)
        A_theta_t = a_t + alg_mult(kappa_t, theta, r)
        y_t = alg_mult(A_theta_t, h, r) + alg_mult(b_t, theta, r) + c_t
        d_t = phi_prime(y_t, r)
        inner = alg_mult(A_theta_t, s, r) + alg_mult(kappa_t, h, r) + b_t
        s = alg_mult(d_t, inner, r)
        h_next = phi(y_t, r)
        y = W @ h_next
        diff = y - targets[t]
        loss_total = loss_total + 0.5 * jnp.sum(diff ** 2)
        dl_dh = W.T @ diff
        g_total = g_total + transpose_mult(s, dl_dh, r)
        h = h_next
    return g_total / T, loss_total / T


def sgd_step(theta, grad, lr):
    return theta - lr * grad


def run_training(r=R, T=128, n_train=60, n_val=15, lr=3.0,
                  seed_teacher=777, seed_init=555, seed_readout=999,
                  seq_seed_offset=10_000, val_seed_offset=90_000):
    print()
    print("=" * 78)
    print(f"B34b teacher/student training, r={r}")
    print("=" * 78)
    gen_params = make_gen_params(seed=1000 + r, r=r)
    grad_bptt_fn = make_grad_bptt_fn()
    W = make_W(seed_readout, r)
    rng_star = np.random.RandomState(seed_teacher)
    theta_star = jnp.array(rng_star.randn(r) * 0.2)
    rng_init = np.random.RandomState(seed_init)
    theta_init = jnp.array(rng_init.randn(r) * 0.2)

    theta_full, theta_reduced, theta_bptt = theta_init, theta_init, theta_init
    train_losses = dict(full=[], reduced=[], bptt=[])
    grad_diag = []
    rank_samples = []

    t_start = time.time()
    for step in range(n_train):
        h0, xs = make_sequence(seq_seed_offset + step, T, r)
        targets = teacher_targets(h0, theta_star, xs, gen_params, r, W)

        g_full, loss_full, S_traj = full_rtrl_grad_mse(theta_full, h0, xs, targets, gen_params, r, W)
        g_reduced, loss_reduced = reduced_algebra_grad_mse(theta_reduced, h0, xs, targets, gen_params, r, W)
        g_bptt = jax.grad(loss_mse)(theta_bptt, h0, xs, targets, gen_params, r, W)
        loss_bptt_val = float(loss_mse(theta_bptt, h0, xs, targets, gen_params, r, W))

        train_losses["full"].append(float(loss_full))
        train_losses["reduced"].append(float(loss_reduced))
        train_losses["bptt"].append(loss_bptt_val)

        if step < 5:
            grad_diag.append(dict(
                step=step,
                diff_full_reduced=float(jnp.linalg.norm(g_full - g_reduced)),
                diff_reduced_bptt=float(jnp.linalg.norm(g_reduced - g_bptt)),
            ))

        if step % 15 == 0:
            sv0 = np.linalg.svd(np.asarray(S_traj[-1]), compute_uv=False)
            s0_val = float(np.asarray(S_traj[-1])[0, 0])
            exact_rank = r if abs(s0_val) > 1e-6 else 0
            rank_samples.append(exact_rank)

        theta_full = sgd_step(theta_full, g_full, lr)
        theta_reduced = sgd_step(theta_reduced, g_reduced, lr)
        theta_bptt = sgd_step(theta_bptt, g_bptt, lr)

        if step < 5:
            grad_diag[-1]["param_diff_full_reduced"] = float(jnp.linalg.norm(theta_full - theta_reduced))
            grad_diag[-1]["param_diff_reduced_bptt"] = float(jnp.linalg.norm(theta_reduced - theta_bptt))

        if step % 10 == 0 or step == n_train - 1:
            print(f"  step={step:4d}  loss_full={loss_full:.6e}  loss_reduced={loss_reduced:.6e}  "
                  f"loss_bptt={loss_bptt_val:.6e}", flush=True)
    elapsed = time.time() - t_start

    val_losses = dict(full=[], reduced=[], bptt=[])
    for i in range(n_val):
        h0, xs = make_sequence(val_seed_offset + i, T, r)
        targets = teacher_targets(h0, theta_star, xs, gen_params, r, W)
        val_losses["full"].append(float(loss_mse(theta_full, h0, xs, targets, gen_params, r, W)))
        val_losses["reduced"].append(float(loss_mse(theta_reduced, h0, xs, targets, gen_params, r, W)))
        val_losses["bptt"].append(float(loss_mse(theta_bptt, h0, xs, targets, gen_params, r, W)))

    print("-" * 78)
    print("First-updates gradient/parameter agreement:")
    for row in grad_diag:
        print(f"  step={row['step']}  ||g_full-g_reduced||={row['diff_full_reduced']:.3e}  "
              f"||g_reduced-g_bptt||={row['diff_reduced_bptt']:.3e}  "
              f"||theta_full-theta_reduced||={row['param_diff_full_reduced']:.3e}  "
              f"||theta_reduced-theta_bptt||={row['param_diff_reduced_bptt']:.3e}")
    print("-" * 78)
    tl = train_losses
    print(f"Initial train loss: {tl['full'][0]:.6e}")
    print(f"Final train loss: full={tl['full'][-1]:.6e}  reduced={tl['reduced'][-1]:.6e}  bptt={tl['bptt'][-1]:.6e}")
    vl = val_losses
    print(f"Mean validation loss ({n_val} held-out): full={np.mean(vl['full']):.6e}  "
          f"reduced={np.mean(vl['reduced']):.6e}  bptt={np.mean(vl['bptt']):.6e}")
    print(f"Sampled EXACT-criterion rank(S_t) during training (every 15 steps): {rank_samples}  "
          f"(all should be {r})")
    print(f"T={T}  n_train={n_train}  elapsed={elapsed:.1f}s")
    print(f"Additional persistent eligibility: full={r*r} floats, reduced={r} floats, ratio={r}x")

    return dict(train_losses=train_losses, val_losses=val_losses, grad_diag=grad_diag,
                rank_samples=rank_samples, T=T, n_train=n_train, elapsed=elapsed,
                gen_params=gen_params, W=W, theta_star=theta_star)


if __name__ == "__main__":
    run_critical_diagnostic()
    run_training()
