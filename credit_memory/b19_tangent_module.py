# Part G: selectivity algebra. Extends B18 Part G: G1 commuting selector
# family (R(q) = R0 + q*Delta, Delta IN the commutant of R0 -- credit
# should stay O(dim A)); G2 noncommuting selector generator confined to
# the shared core (Delta generic, not commuting -- credit may grow toward
# r^2 but should stay INDEPENDENT of n); G3 unrestricted (reproduces B17/
# B18's wide-state blowup, not retested here -- see those phases).
# ---------------------------------------------------------------------------
def sigmoid(z):
    return 1.0 / (1.0 + np.exp(-z))


def dsigmoid(z):
    s = sigmoid(z)
    return s * (1 - s)


def part_g_selectivity_algebra(n_list, r=4, N0=8, T_=30, seed=0, c_gate=1.0,
                               selector_kind="commuting"):
    rng = np.random.RandomState(seed)
    results = []
    R0 = arch_commuting_diag(r, rng)[0] * 0.85
    if selector_kind == "commuting":
        Delta = arch_commuting_diag(r, rng)[1][0]  # one commuting direction
    elif selector_kind == "noncommuting":
        Delta = rng.randn(r, r)
    else:
        raise ValueError(selector_kind)

    for n in n_list:
        N1 = n * r
        u = rng.randn(T_, N0)
        B = rng.randn(N1, N0) / np.sqrt(N0)
        theta0 = np.ones(N0)
        a0 = 0.85

        def R_of(q):
            return R0 + q * Delta

        def simulate(theta, gate_kind):
            h0 = np.zeros(N0); h1 = np.zeros((n, r))
            for t in range(T_):
                h0 = a0 * h0 + theta * u[t]
                if gate_kind == "G1_nonselective":
                    R_t = R0
                elif gate_kind == "G2_exogenous":
                    R_t = R_of(c_gate * np.sin(0.3 * t))
                else:  # G3_endogenous
                    R_t = R_of(c_gate * np.mean(h0))
                Bh0 = (B @ h0).reshape(n, r)
                h1 = h1 @ R_t.T + Bh0
            return h1.reshape(-1)

        eps = 1e-5
        for gate_kind in ("G1_nonselective", "G2_exogenous", "G3_endogenous"):
            J_fd = np.zeros((N1, N0))
            for m in range(N0):
                tp = theta0.copy(); tp[m] += eps
                tm = theta0.copy(); tm[m] -= eps
                J_fd[:, m] = (simulate(tp, gate_kind) - simulate(tm, gate_kind)) / (2 * eps)

            h0 = np.zeros(N0)
            R_t_seq, h0_seq = [], []
            for t in range(T_):
                h0 = a0 * h0 + theta0 * u[t]
                if gate_kind == "G1_nonselective":
                    R_t = R0
                elif gate_kind == "G2_exogenous":
                    R_t = R_of(c_gate * np.sin(0.3 * t))
                else:
                    R_t = R_of(c_gate * np.mean(h0))
                R_t_seq.append(R_t); h0_seq.append(h0.copy())
            h1_true = np.zeros((n, r)); h1_traj = []
            for t in range(T_):
                Bh0 = (B @ h0_seq[t]).reshape(n, r)
                h1_true = h1_true @ R_t_seq[t].T + Bh0
                h1_traj.append(h1_true.copy())
            h1_prev_traj = [np.zeros((n, r))] + h1_traj[:-1]

            J_corrected = np.zeros((N1, N0))
            for m in range(N0):
                z = 0.0; W = B[:, m].reshape(n, r); s = np.zeros((n, r))
                for t in range(T_):
                    z = a0 * z + u[t, m]
                    if gate_kind == "G3_endogenous":
                        extra = (h1_prev_traj[t] @ Delta.T) * (c_gate / N0 * z)
                    else:
                        extra = 0.0
                    s = s @ R_t_seq[t].T + extra + W * z
                J_corrected[:, m] = s.reshape(-1)

            scale = float(np.max(np.abs(J_fd)) + 1e-30)
            gap_corr = float(np.max(np.abs(J_fd - J_corrected)))
            # measured rank of the correction term's own spatial trajectory
            traj_mat = np.stack(h1_prev_traj, axis=0).reshape(T_, -1)
            sv = np.linalg.svd(traj_mat, compute_uv=False)
            traj_rank = int(np.sum(sv > 1e-9 * sv[0])) if len(sv) and sv[0] > 0 else 0
            results.append(dict(selector_kind=selector_kind, n=n, N1=N1, gate=gate_kind,
                                gap_corrected_rel=gap_corr / scale, h1_traj_rank=traj_rank))
    return results
