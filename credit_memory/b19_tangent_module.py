"""Phase B19 -- minimal tangent credit module. Tests whether the exact
online-credit dimension for a temporal core R is controlled by the
two-sided tangent bimodule

    B = A P A,   A = span{I, R, R^2, ...} (algebra generated by R),
                 P = span of trainable temporal-parameter tangents
                     dR/dtheta_k (as r x r matrices),

rather than defaulting to r^2 (B18's dense-storage K-chain). Key
reframing found while building this: B18's K-chain used P = span{I}
(the SOURCE-injection tangent, generically commuting with R) and
stored it as a dense r x r matrix -- r^2 numbers -- even though the
theory here predicts the TRUE minimal dimension for a commuting
tangent is dim(A) <= r, not r^2. B18's r^2 was a measured SUFFICIENT
(storage) cost, never verified as MINIMAL. This phase verifies that
distinction directly, plus the separate (and generically much larger)
question of R's OWN trainable-entry tangents.

All dimension claims are verified two ways: (i) algebraically, via
rank-revealing SVD on explicit bases of A and B = APA; (ii) exact
sensitivity simulation (linear system, exact-by-linearity, matching
B16.2/B18's established style) compared against the reduced-dimension
"minimal online recursion" built directly from the measured basis of
B, to machine precision.

Run:  python -m credit_memory.b19_tangent_module
"""
from __future__ import annotations

import numpy as np


# ---------------------------------------------------------------------------
# Part A/B core: algebra + bimodule dimension via rank-revealing SVD
# ---------------------------------------------------------------------------
def matrix_powers(R, max_k=None):
    r = R.shape[0]
    max_k = r if max_k is None else max_k  # Cayley-Hamilton bounds degree <= r
    powers = [np.eye(r, dtype=R.dtype)]
    Rk = np.eye(r, dtype=R.dtype)
    for _ in range(1, max_k):
        Rk = Rk @ R
        powers.append(Rk)
    return powers


def subspace_basis(mats, tol=1e-9):
    """Rank-revealing SVD basis for span{mats} (each an r x r matrix),
    vectorized. Returns (orthonormal basis rows, singular values, rank)."""
    vecs = np.stack([M.ravel() for M in mats], axis=0)
    U, S, Vt = np.linalg.svd(vecs, full_matrices=False)
    if len(S) == 0 or S[0] < 1e-300:
        return Vt[:0], S, 0
    rank = int(np.sum(S > tol * S[0]))
    return Vt[:rank], S, rank


def algebra_basis(R, tol=1e-9):
    """A = span{I, R, R^2, ...}."""
    return subspace_basis(matrix_powers(R), tol=tol)


def bimodule_basis(R, E_list, tol=1e-9):
    """B = A P A = span{R^a E_i R^b : 0<=a,b<=r-1, E_i in P}."""
    r = R.shape[0]
    powers = matrix_powers(R)
    mats = []
    for E in E_list:
        for a in range(r):
            for b in range(r):
                mats.append(powers[a] @ E @ powers[b])
    return subspace_basis(mats, tol=tol)


def predicted_dims(R, E_list, tol=1e-9):
    _, Sa, dimA = algebra_basis(R, tol=tol)
    _, Sb, dimB = bimodule_basis(R, E_list, tol=tol)
    return dict(dim_A=dimA, dim_P=len(E_list), dim_APA=dimB, r=R.shape[0])


# ---------------------------------------------------------------------------
# Minimal online recursion built directly from a measured basis of B:
# since R*(R^a E R^b) = R^{a+1} E R^b stays in span{R^c E R^b} (closed
# under left-mult by R via Cayley-Hamilton reduction), B is a LEFT
# A-module -- multiplication by R acts on B via a d x d matrix R_B
# (d = dim B) in the measured basis. The minimal exact online credit
# recursion is then coords_t = R_B @ coords_{t-1} + inject(u_t), a
# genuinely d-dimensional (not r^2-dimensional) linear recursion.
# ---------------------------------------------------------------------------
def build_minimal_recursion(R, E_list, tol=1e-9):
    basis, S, d = bimodule_basis(R, E_list, tol=tol)  # d x r^2, orthonormal rows
    r = R.shape[0]
    if d == 0:
        return dict(d=0, basis=basis, R_B=np.zeros((0, 0)), inject=[])
    # R_B: express R @ M_j (for each basis vector M_j, reshaped to r x r) in
    # the same basis via least-squares (exact since R@B subset B).
    R_B = np.zeros((d, d))
    for j in range(d):
        Mj = basis[j].reshape(r, r)
        RMj = R @ Mj
        coords, *_ = np.linalg.lstsq(basis.T, RMj.ravel(), rcond=None)
        R_B[:, j] = coords
    # injection vectors: for each E_i, the "instantaneous" contribution E_i
    # itself, expressed in the basis (a=b=0 term of the generating set).
    inject = []
    for E in E_list:
        coords, *_ = np.linalg.lstsq(basis.T, E.ravel(), rcond=None)
        inject.append(coords)
    return dict(d=d, basis=basis, R_B=R_B, inject=inject)


def verify_minimal_recursion(R, E_list, T_=30, n_sources=6, seed=0, tol=1e-9):
    """Exact verification: true full-matrix K_t (=sum u_t^i R^{t-tau} E_i,
    literal (r,r) simulation) vs. the reduced d-dim recursion built from
    the measured basis of B, projected back to (r,r) for comparison."""
    rng = np.random.RandomState(seed)
    r = R.shape[0]
    rec = build_minimal_recursion(R, E_list, tol=tol)
    d = rec["d"]
    max_err = 0.0
    for _ in range(n_sources):
        u = rng.randn(T_, len(E_list))
        K_true = np.zeros((r, r))
        coords = np.zeros(d)
        for t in range(T_):
            K_true = R @ K_true
            for i, E in enumerate(E_list):
                K_true = K_true + u[t, i] * E
            if d > 0:
                coords = rec["R_B"] @ coords
                for i in range(len(E_list)):
                    coords = coords + u[t, i] * rec["inject"][i]
                K_pred = (coords @ rec["basis"]).reshape(r, r)
            else:
                K_pred = np.zeros((r, r))
            err = float(np.max(np.abs(K_true - K_pred)))
            max_err = max(max_err, err)
    return max_err, d


